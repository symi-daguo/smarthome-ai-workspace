/**
 * 提交幂等键生成器。
 *
 * 用途：生图 / 生视频 / 方案这类**会扣额度**的提交，弱网超时后重试、
 * 切走再回来重发、跨标签页重复点，都会造成重复扣费。
 * 带同一个键重放，后端命中已有产物直接返回（deduped=true），不再出图也不再扣额度。
 *
 * 配合原则：**失败保留键、成功清除**——
 * - 超时（不知道成没成）：保留键重放，后端有记录就取回，没有就真生成
 * - 业务失败（后端未建记录）：复用同一个键也无害，下一次会真生成
 * - 成功：清掉，下一次是全新请求（用户多半是改了提示词想再来一张）
 *
 * 真防线在后端的唯一约束，前端这层只为体验；换浏览器或清了缓存，
 * 后端仍能挡住重复提交。
 */
export function newRequestId(): string {
  return globalThis.crypto?.randomUUID?.() ?? `r-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}
