-- 预算分配建议落库
--
-- 背景：方案工作台第一步有一张「预算分配建议」条，按六大生态给出建议占比与金额，
-- 门店可以直接改金额。这个金额此前**只活在浏览器内存里**：
-- 改完刷新就丢，方案里没有、Agent 也够不着 —— 客户拿到的预算页与门店改过的数字对不上。
--
-- 为什么是 JSONB 而不是六列：
-- 它本来就是一张「生态 → 金额」的表，拆成六列会让「新增一个生态」
-- 变成一次加列迁移 + 改六处代码。
--
-- 为什么不在后端校验生态名：
-- 生态清单的唯一来源在前端 data/planThemes.ts 的 ECOSYSTEM_SPLIT，
-- 后端再抄一份枚举必然与前端漂移（前端加了生态、后端就开始拒收）。
-- 后端只校验取值形态（键是短标识、值是非负有限数、条数有上限）。
--
-- 用 IF NOT EXISTS：开发库可能被手工改过，裸 ALTER 撞上已存在的列会直接报错，
-- 容器启动时 migrate deploy 失败、整个 api 起不来。幂等写法让重复执行安全。
ALTER TABLE "PlanProject" ADD COLUMN IF NOT EXISTS "budgetSplit" JSONB NOT NULL DEFAULT '{}';
