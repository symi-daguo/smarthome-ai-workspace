-- 安装调试费率（百分比）：报价清单里「安装调试费」按设备参考零售合计的百分比计取
--
-- 为什么存在租户上而不是写死在代码里：每家门店的施工与调试成本不同
-- （是否含布线、是否含拆旧、是否含上门次数），费率必须由门店自己定。
-- 放在租户上，报价计算时后端按当前租户的费率算，PPTX / 讲稿 / 分享页三处同源。
--
-- 默认 20：行业经验值是设备价的 15%~25%，20% 居中。
-- 老数据在默认值上即自动生效，不需要回填脚本。
-- 用 IF NOT EXISTS：开发库可能被手工改过，裸 ADD COLUMN 遇到列已存在会直接报错，
-- 容器启动时 migrate deploy 失败、整个 api 起不来。幂等写法让重复执行安全。
ALTER TABLE "Tenant"
  ADD COLUMN IF NOT EXISTS "installRate" INTEGER NOT NULL DEFAULT 20;
